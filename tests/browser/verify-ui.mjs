import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('test-results/ui', {recursive:true});
const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || 'chrome'});
const page=await browser.newPage();
const base=process.env.SITE_URL || 'http://127.0.0.1:5173/';
const run=async (page) => {
  const results=[];
  const record=(name,passed,detail='')=>{results.push({name,passed,detail});if(!passed)throw new Error(name+': '+detail)};
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base);
  await page.locator('.culture-sculpture.is-ready').waitFor();
  record('Exact navigation',JSON.stringify(await page.locator('.bottom-nav a span').allTextContents())===JSON.stringify(['Home','World','Time Machine','Live','Movies','Music','Sports','Gaming','News','Fashion','Culture','Kids','My World']));
  await page.screenshot({path:'test-results/ui/monumental-desktop.png',fullPage:true});
  await page.getByRole('link',{name:'Search',exact:true}).click();
  await page.getByRole('combobox',{name:'Search everything'}).fill('Tokyo');
  await page.getByRole('button',{name:'Full catalogue',exact:true}).click();
  await page.waitForURL('**q=Tokyo');
  await page.locator('.browse-page').waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.film-card').length===1);
  record('Search narrows catalogue',(await page.locator('.film-card').count())===1);
  await page.getByLabel('Destination',{exact:true}).selectOption('miami');
  await page.waitForURL('**place=miami');
  await page.locator('.empty-collection').waitFor();
  record('Combined filters intersect',await page.locator('.empty-collection').isVisible());
  await page.getByRole('button',{name:'Reset filters'}).click();
  await page.waitForURL('**#/search');
  await page.waitForFunction(()=>document.querySelectorAll('.film-card').length===14);
  record('Reset restores 14 records',(await page.locator('.film-card').count())===14);
  const save=page.getByRole('button',{name:'Save Miami, in Frequency',exact:true});
  if(await save.count())await save.click();
  await page.getByRole('button',{name:'Play Miami, in Frequency',exact:true}).click();
  const video=page.locator('.ms-player-dialog video');
  await video.waitFor();
  await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
  record('Local video loads',await video.evaluate(v=>v.duration>30&&v.duration<35));
  if (await video.evaluate(v=>v.paused)) await page.getByRole('button',{name:'Play video',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>1);
  await page.getByRole('button',{name:'Pause video',exact:true}).click();
  record('Real playback advances',await video.evaluate(v=>v.currentTime>1&&v.paused));
  await page.getByLabel('Playback speed').selectOption('1.5');
  record('Playback speed',await video.evaluate(v=>v.playbackRate===1.5));
  await video.evaluate(v=>{v.currentTime=12;v.dispatchEvent(new Event('timeupdate'))});
  record('Captions loaded',(await video.locator('track').count())>0);
  await page.screenshot({path:'test-results/ui/monumental-player.png'});
  await page.keyboard.press('Escape');
  record('Player Escape closes',!(await page.locator('.ms-player-dialog').count()));
  await page.getByRole('link',{name:'My World',exact:true}).click();
  await page.waitForURL('**#/my-world');
  await page.locator('.my-world').waitFor();
  record('Saved film appears',await page.locator('.film-card').filter({hasText:'Miami, in Frequency'}).isVisible());
  await page.reload();
  await page.locator('.film-card').first().waitFor();
  record('Saved films persist',await page.locator('.film-card').filter({hasText:'Miami, in Frequency'}).isVisible());
  await page.getByRole('tab',{name:'Continue watching'}).click();
  record('Resume collection populated',(await page.locator('.film-card').count())>0);
  await page.goto(base+'#/journey');
  await page.getByRole('button',{name:'Find my journey'}).click();
  record('Journey generated',(await page.locator('.journey-stops .journey-stop').count())>0);
  await page.getByRole('button',{name:'Save journey',exact:true}).click();
  record('Journey save state',await page.getByRole('button',{name:'Saved to My World'}).isDisabled());
  await page.getByRole('link',{name:'My World',exact:true}).click();
  record('Journey in My World',await page.locator('.saved-journeys').isVisible());
  await page.goto(base+'#/settings');
  await page.getByRole('switch',{name:'Interface sound'}).click();
  record('Sound enabled',await page.getByRole('switch',{name:'Interface sound'}).getAttribute('aria-checked')==='true');
  await page.getByRole('switch',{name:'Interface sound'}).click();
  await page.getByRole('switch',{name:'Reduce motion'}).click();
  record('Reduced motion applied',await page.locator('html').getAttribute('data-motion')==='reduced');
  await page.getByRole('switch',{name:'Reduce motion'}).click();
  for(const category of ['movies','music','sports','gaming','news','fashion','culture','kids']){
    await page.goto(base+'#/category/'+category);
    await page.locator('h1').waitFor();
    record('Category '+category,(await page.locator('h1').textContent()).toLowerCase()===category);
    record('No overflow '+category,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  }
  await page.setViewportSize({width:390,height:844});
  for(const route of ['/','/search','/my-world','/journey','/live','/premium','/settings','/film/miami-frequency','/film/wavemakers-valid-id']){
    await page.goto(base+'#'+route);
    await page.locator('h1').waitFor();
    record('Mobile no overflow '+route,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  }
  await page.goto(base);
  await page.locator('.culture-sculpture.is-ready').waitFor();
  await page.screenshot({path:'test-results/ui/monumental-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Open all categories'}).click();
  record('Mobile index opens',await page.getByRole('dialog').isVisible());
  await page.getByRole('dialog').getByRole('link',{name:/Gaming/}).click();
  await page.waitForURL('**#/category/gaming');
  record('Mobile index route works',!(await page.getByRole('dialog').isVisible()));
  return results;
}
;
try { const results=await run(page); await writeFile('test-results/ui/results.json',JSON.stringify(results,null,2)); console.log(`${results.length} UI checks passed`); } finally { await browser.close(); }