import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const out = '.openai/integration-review'; await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage(); const errors = []; const results = [];
page.on('pageerror', error => errors.push(error.message));
const base = 'http://127.0.0.1:5173';
try {
  await page.goto(base + '/');
  await page.getByRole('link', { name: 'Search', exact: true }).click();
  const deck = page.locator('dialog.command-deck'); await deck.waitFor({ state: 'visible' });
  const search = deck.getByRole('combobox', { name: 'Search everything' });
  await search.fill('Miami');
  assert.ok(await deck.getByRole('option').count() > 1);
  await page.screenshot({ path: out + '/command-desktop.png' });
  await search.fill('Time Machine'); await search.press('Enter');
  await page.waitForURL(/#\/time-machine/);
  results.push('Command deck searches destinations, stories and pages, and Enter navigates correctly.');
  await page.getByRole('link', { name: 'Search', exact: true }).click(); await search.fill('zzz-no-such-story');
  assert.equal(await deck.getByRole('option').count(), 0);
  await page.keyboard.press('Escape');
  assert.equal(await deck.isVisible(), false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('link', { name: 'Search', exact: true }).click(); await search.fill('Miami');
  await page.screenshot({ path: out + '/command-mobile.png' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Open sound studio', exact: true }).click();
  await page.screenshot({ path: out + '/studio-mobile-context.png' });
  await page.keyboard.press('Escape');
  results.push('Mobile search and sound panel fit the viewport; Escape closes each.');
  await page.setViewportSize({ width: 1440, height: 1000 });

  await page.goto(base + '/#/search?q=miami');
  const firstCard = page.locator('.film-card').first();
  await firstCard.locator('.film-image').hover();
  await page.waitForFunction(() => { const video = document.querySelector('.film-card .card-video'); return video && video.currentTime > 0.1 && video.muted; });
  const previewHistory = await page.evaluate(() => JSON.parse(localStorage.getItem('monumental.viewer.v1') || '{}').history || {});
  assert.equal(Object.keys(previewHistory).length, 0, 'Silent previews do not enter viewing history');
  await page.mouse.move(1400, 100);
  await page.waitForFunction(() => !document.querySelector('.card-video'));
  await firstCard.getByRole('button', { name: /Preview .* silently/ }).click();
  await page.waitForFunction(() => document.querySelector('.card-video'));
  await firstCard.getByRole('button', { name: /^Play / }).click();
  await page.locator('.ms-player-dialog').waitFor({ state: 'visible' });
  assert.equal(await page.locator('.card-video').count(), 0, 'Opening the player stops the card preview');
  await page.keyboard.press('Escape');
  results.push('Card preview is muted, stops on exit, never updates history, and yields to the actual player.');

  await page.goto(base + '/#/journey');
  await page.getByRole('button', { name: 'Find my journey' }).click();
  const stops = await page.locator('.journey-stop').count(); assert.ok(stops > 1);
  await page.getByRole('button', { name: 'Play entire journey' }).click();
  const player = page.locator('.ms-player-dialog');
  await player.waitFor({ state: 'visible' });
  await page.waitForFunction(() => { const media = document.querySelector('.ms-player-dialog video'); return media && media.readyState >= 2 && Number.isFinite(media.duration); });
  const media = player.locator('video');
  if (await player.getByRole('button', { name: 'Pause video', exact: true }).count()) await player.getByRole('button', { name: 'Pause video', exact: true }).click();
  await player.getByRole('slider', { name: 'Seek video' }).fill('14');
  assert.ok(Math.abs(await media.evaluate(video => video.currentTime) - 14) < 0.5);
  await player.getByRole('button', { name: 'Back 10 seconds' }).click();
  assert.ok(Math.abs(await media.evaluate(video => video.currentTime) - 4) < 0.5);
  await player.getByRole('button', { name: 'Forward 10 seconds' }).click();
  assert.ok(Math.abs(await media.evaluate(video => video.currentTime) - 14) < 0.5);
  await page.evaluate(() => { navigator.clipboard.writeText = async value => { window.__copiedMoment = value; }; });
  await player.getByRole('button', { name: 'Copy link to this moment' }).click();
  const share = await page.evaluate(() => window.__copiedMoment);
  assert.match(share, /\/film\/[^?]+\?t=14/);
  assert.equal(await player.getByRole('region', { name: 'Journey queue' }).getByRole('button', { name: /^Journey stop/ }).count(), stops);
  await player.getByRole('button', { name: /^Journey stop 2:/ }).click();
  await page.waitForFunction(() => document.querySelector('.ms-queue-stops button:nth-child(2)')?.getAttribute('aria-current') === 'step');
  const auto = player.getByRole('switch', { name: 'Auto-continue journey' });
  assert.equal(await auto.getAttribute('aria-checked'), 'true');
  await auto.click(); assert.equal(await auto.getAttribute('aria-checked'), 'false');
  await page.screenshot({ path: out + '/queue-player-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: out + '/queue-player-mobile.png' });
  const overflow = await player.evaluate(dialog => ({ width: dialog.clientWidth, scroll: dialog.scrollWidth, viewport: innerWidth }));
  assert.ok(overflow.scroll <= overflow.width + 1, 'Player has no horizontal overflow');
  await page.keyboard.press('Escape');
  results.push('Real playback seek and ±10 controls work; copied moment contains t=14; ordered queue can skip and disable auto-continue.');
  await page.goto(share);
  await page.getByRole('button', { name: 'Watch from 0:14', exact: true }).click();
  await page.waitForFunction(() => { const video = document.querySelector('.ms-player-dialog video'); return video && video.currentTime >= 14; });
  results.push('Shared moment opens the film at the requested time after viewer activation.');
  assert.deepEqual(errors, []);
  await writeFile(out + '/report.json', JSON.stringify({ passed: true, results, errors }, null, 2));
  console.log(JSON.stringify({ passed: true, results, errors }, null, 2));
} finally { await browser.close(); }
